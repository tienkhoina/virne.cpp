double
NumpyRandomState::exponential(
    double scale)
{
    if (scale < 0.0)
    {
        throw std::invalid_argument(
            "exponential scale must be non-negative");
    }

    return
        scale
        * -std::log(
            1.0 - random());
}

std::vector<double>
NumpyRandomState::exponential(
    double scale,
    std::size_t size)
{
    if (scale < 0.0)
    {
        throw std::invalid_argument(
            "exponential scale must be non-negative");
    }

    std::vector<double> result =
        direct_output_vector<double>(size);
    fill_random(result.data(), result.size());
    double* const output = result.data();
    parallel_chunks(
        result.size(),
        [=](std::size_t begin, std::size_t end)
        {
            for (std::size_t index = begin;
                 index < end;
                 ++index)
            {
                output[index] =
                    scale * -std::log(
                        1.0 - output[index]);
            }
        });
    return result;
}

