double
NumpyRandomState::log_gamma(
    double value)
{
    static constexpr double coefficients[10] =
    {
        8.333333333333333e-02,
        -2.777777777777778e-03,
        7.936507936507937e-04,
        -5.952380952380952e-04,
        8.417508417508418e-04,
        -1.917526917526918e-03,
        6.410256410256410e-03,
        -2.955065359477124e-02,
        1.796443723688307e-01,
        -1.39243221690590e+00
    };

    std::int64_t n = 0;
    if (value == 1.0 || value == 2.0)
    {
        return 0.0;
    }
    if (value < 7.0)
    {
        n = static_cast<std::int64_t>(
            7.0 - value);
    }

    double x0 =
        value + static_cast<double>(n);
    const double x2 =
        (1.0 / x0) * (1.0 / x0);

    double series = coefficients[9];
    for (int i = 8; i >= 0; --i)
    {
        series *= x2;
        series += coefficients[i];
    }

    double result =
        series / x0
        + 0.5 * 1.8378770664093453e+00
        + (x0 - 0.5) * std::log(x0)
        - x0;

    if (value < 7.0)
    {
        for (std::int64_t i = 1; i <= n; ++i)
        {
            result -= std::log(x0 - 1.0);
            x0 -= 1.0;
        }
    }

    return result;
}

std::int64_t
NumpyRandomState::poisson_unchecked(
    double lambda)
{
    if (lambda == 0.0)
    {
        return 0;
    }

    if (lambda < 10.0)
    {
        const double threshold =
            std::exp(-lambda);

        std::int64_t value = 0;
        double product = 1.0;

        while (true)
        {
            product *= random();
            if (product > threshold)
            {
                ++value;
            }
            else
            {
                return value;
            }
        }
    }

    const double root =
        std::sqrt(lambda);
    const double log_lambda =
        std::log(lambda);
    const double b =
        0.931 + 2.53 * root;
    const double a =
        -0.059 + 0.02483 * b;
    const double inverse_alpha =
        1.1239 + 1.1328 / (b - 3.4);
    const double vr =
        0.9277 - 3.6224 / (b - 2.0);

    while (true)
    {
        const double u =
            random() - 0.5;
        const double v =
            random();
        const double us =
            0.5 - std::fabs(u);

        // The upstream cast after division by us relies on the platform's
        // floating-to-integer behavior when the exact RNG endpoint makes
        // us==0.  That candidate is always rejected, so reject it explicitly
        // after consuming the same two doubles and avoid undefined C++.
        if (us == 0.0)
        {
            continue;
        }

        const double candidate_value =
            std::floor(
                (2.0 * a / us + b) * u
                + lambda
                + 0.43);
        std::int64_t candidate = 0;
        if (!checked_poisson_candidate(
                candidate_value, candidate))
        {
            continue;
        }

        if (us >= 0.07 && v <= vr)
        {
            return candidate;
        }

        if (us < 0.013 && v > us)
        {
            continue;
        }

        if (std::log(v)
                + std::log(inverse_alpha)
                - std::log(a / (us * us) + b)
            <= -lambda
                + static_cast<double>(candidate) * log_lambda
                - log_gamma(
                    static_cast<double>(candidate) + 1.0))
        {
            return candidate;
        }
    }
}

std::int64_t
NumpyRandomState::poisson(
    double lambda)
{
    const double integer_max =
        static_cast<double>(
            std::numeric_limits<std::int64_t>::max());
    const double lambda_max =
        integer_max
        - 10.0 * std::sqrt(integer_max);

    if (!std::isfinite(lambda)
        || lambda < 0.0
        || lambda > lambda_max)
    {
        throw std::invalid_argument(
            "poisson lambda must be finite, non-negative, and representable");
    }

    return poisson_unchecked(lambda);
}

std::vector<std::int64_t>
NumpyRandomState::poisson(
    double lambda,
    std::size_t size)
{
    // Validate before consuming any state, as RandomState does.
    const double integer_max =
        static_cast<double>(
            std::numeric_limits<std::int64_t>::max());
    const double lambda_max =
        integer_max
        - 10.0 * std::sqrt(integer_max);

    if (!std::isfinite(lambda)
        || lambda < 0.0
        || lambda > lambda_max)
    {
        throw std::invalid_argument(
            "poisson lambda must be finite, non-negative, and representable");
    }

    std::vector<std::int64_t> result =
        direct_output_vector<std::int64_t>(size);
    if (result.empty())
    {
        return result;
    }
    std::int64_t* output = result.data();
    std::int64_t* const output_end =
        output + result.size();

    if (lambda == 0.0)
    {
        std::fill(output, output_end, std::int64_t{0});
        return result;
    }

    if (lambda < 10.0)
    {
        const double threshold =
            std::exp(-lambda);
        while (output != output_end)
        {
            std::int64_t value = 0;
            double product = 1.0;
            while (true)
            {
                product *= random();
                if (product > threshold)
                {
                    ++value;
                }
                else
                {
                    *output++ = value;
                    break;
                }
            }
        }
        return result;
    }

    const double root = std::sqrt(lambda);
    const double log_lambda = std::log(lambda);
    const double b = 0.931 + 2.53 * root;
    const double a = -0.059 + 0.02483 * b;
    const double inverse_alpha =
        1.1239 + 1.1328 / (b - 3.4);
    const double log_inverse_alpha =
        std::log(inverse_alpha);
    const double vr =
        0.9277 - 3.6224 / (b - 2.0);

    while (output != output_end)
    {
        while (true)
        {
            const double u = random() - 0.5;
            const double v = random();
            const double us = 0.5 - std::fabs(u);
            if (us == 0.0)
            {
                continue;
            }

            const double candidate_value =
                std::floor(
                    (2.0 * a / us + b) * u +
                    lambda + 0.43);
            std::int64_t candidate = 0;
            if (!checked_poisson_candidate(
                    candidate_value, candidate))
            {
                continue;
            }

            if (us >= 0.07 && v <= vr)
            {
                *output++ = candidate;
                break;
            }
            if (us < 0.013 && v > us)
            {
                continue;
            }

            if (std::log(v) + log_inverse_alpha -
                    std::log(a / (us * us) + b)
                <= -lambda +
                    static_cast<double>(candidate) * log_lambda -
                    log_gamma(
                        static_cast<double>(candidate) + 1.0))
            {
                *output++ = candidate;
                break;
            }
        }
    }
    return result;
}

NdArray<std::int64_t>
NumpyRandomState::poisson(
    double lambda,
    const Shape& shape)
{
    const std::size_t size =
        NdArray<std::int64_t>::checked_size(shape);
    auto values = poisson(
        lambda,
        size);
    return NdArray<std::int64_t>(
        shape,
        std::move(values));
}

