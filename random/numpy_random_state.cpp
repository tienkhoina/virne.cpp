NumpyRandomState::NumpyRandomState(
    std::uint32_t seed_value)
{
    seed(seed_value);
}

void
NumpyRandomState::seed(
    std::uint32_t seed_value)
{
    // NumPy RandomState's scalar legacy seeding is the original MT19937
    // init_genrand recurrence, not CPython's init_by_array path.
    for (std::size_t i = 0; i < StateSize; ++i)
    {
        state_[i] = seed_value;
        seed_value =
            1812433253U
            * (seed_value ^ (seed_value >> 30))
            + static_cast<std::uint32_t>(i + 1);
    }

    position_ = StateSize;
    has_gauss_ = false;
    gauss_ = 0.0;
}

void
NumpyRandomState::twist()
{
    std::uint32_t* const state =
        state_.data();
    std::size_t i = 0;

    for (; i < StateSize - StateMiddle; ++i)
    {
        const std::uint32_t y =
            (state[i] & UpperMask)
            | (state[i + 1] & LowerMask);

        state[i] =
            state[i + StateMiddle]
            ^ (y >> 1)
            ^ ((0U - (y & 1U)) & MatrixA);
    }

    for (; i < StateSize - 1; ++i)
    {
        const std::uint32_t y =
            (state[i] & UpperMask)
            | (state[i + 1] & LowerMask);

        state[i] =
            state[i - (StateSize - StateMiddle)]
            ^ (y >> 1)
            ^ ((0U - (y & 1U)) & MatrixA);
    }

    const std::uint32_t y =
        (state[StateSize - 1] & UpperMask)
        | (state[0] & LowerMask);

    state[StateSize - 1] =
        state[StateMiddle - 1]
        ^ (y >> 1)
        ^ ((0U - (y & 1U)) & MatrixA);

    const std::uint32_t* input = state_.data();
    std::uint32_t* output = tempered_.data();
    for (std::size_t index = 0;
         index < StateSize;
         ++index)
    {
        output[index] = temper_mt(input[index]);
    }
    position_ = 0;
}

std::uint32_t
NumpyRandomState::next_uint32()
{
    if (position_ == StateSize)
    {
        twist();
    }

    return tempered_[position_++];
}

std::uint64_t
NumpyRandomState::next_uint64()
{
    return
        (static_cast<std::uint64_t>(
            next_uint32()) << 32)
        | static_cast<std::uint64_t>(
            next_uint32());
}

double
NumpyRandomState::random()
{
    if (position_ + 1 < StateSize)
    {
        const std::uint32_t* const state =
            tempered_.data() + position_;
        position_ += 2;
        return random_from_tempered_words(
            state[0], state[1]);
    }

    // Preserve the exact stream when a double straddles a twist boundary.
    const std::uint32_t first = next_uint32();
    const std::uint32_t second = next_uint32();
    const std::uint32_t a = first >> 5;
    const std::uint32_t b = second >> 6;
    return
        (static_cast<double>(a) * 67108864.0
         + static_cast<double>(b))
        / 9007199254740992.0;
}

void
NumpyRandomState::fill_random(
    double* output,
    std::size_t size)
{
    if (size == 0)
    {
        return;
    }

    double* current = output;
    double* const end = output + size;

    while (current != end)
    {
        if (position_ == StateSize)
        {
            twist();
        }

        const std::size_t available_pairs =
            (StateSize - position_) / 2;
        const std::size_t requested =
            static_cast<std::size_t>(end - current);
        const std::size_t count =
            std::min(available_pairs, requested);

        const std::uint32_t* state =
            tempered_.data() + position_;
        double* const chunk_end = current + count;
        while (current != chunk_end)
        {
            *current++ = random_from_tempered_words(
                state[0], state[1]);
            state += 2;
        }
        position_ += count * 2;

        if (count == 0)
        {
            // Exactly one word remains in this state block.
            *current++ = random();
        }
    }
}

std::vector<double>
NumpyRandomState::random(
    std::size_t size)
{
    std::vector<double> result =
        direct_output_vector<double>(size);
    fill_random(result.data(), result.size());
    return result;
}

