constexpr std::uint32_t MatrixA = 0x9908b0dfU;
constexpr std::uint32_t UpperMask = 0x80000000U;
constexpr std::uint32_t LowerMask = 0x7fffffffU;

inline std::uint32_t temper_mt(
    std::uint32_t value) noexcept
{
    value ^= value >> 11;
    value ^= (value << 7) & 0x9d2c5680U;
    value ^= (value << 15) & 0xefc60000U;
    value ^= value >> 18;
    return value;
}

inline double random_from_tempered_words(
    std::uint32_t first,
    std::uint32_t second) noexcept
{
    const std::uint32_t a =
        first >> 5;
    const std::uint32_t b =
        second >> 6;
    return
        (static_cast<double>(a) * 67108864.0
         + static_cast<double>(b))
        / 9007199254740992.0;
}

std::uint64_t bit_mask(std::uint64_t value)
{
    value |= value >> 1;
    value |= value >> 2;
    value |= value >> 4;
    value |= value >> 8;
    value |= value >> 16;
    value |= value >> 32;
    return value;
}

double kahan_sum(
    const std::vector<double>& values)
{
    if (values.empty())
    {
        return 0.0;
    }

    double sum = values.front();
    double compensation = 0.0;

    for (std::size_t i = 1; i < values.size(); ++i)
    {
        const double y =
            values[i] - compensation;
        const double next =
            sum + y;

        compensation =
            (next - sum) - y;
        sum = next;
    }

    return sum;
}

bool checked_poisson_candidate(
    double value,
    std::int64_t& result) noexcept
{
    // static_cast<int64_t>(double) is undefined outside the destination
    // range. INT64_MAX rounds to 2^63 as a double, so use that exact value as
    // an exclusive upper bound before performing the conversion. This also
    // rejects NaN/infinity generated by an extreme PTRS proposal.
    constexpr double Int64ExclusiveUpper = 0x1p63;
    if (!(value >= 0.0 && value < Int64ExclusiveUpper))
    {
        return false;
    }
    result = static_cast<std::int64_t>(value);
    return true;
}

// std::vector(size) performs a full zero-fill before a distribution
// immediately overwrites every scalar. NumPy's C kernels allocate an
// uninitialized contiguous output buffer instead. For the pinned GNU C++
// deployment, start the lifetime of trivial scalars without value-initializing
// them, advance libstdc++'s finish pointer, then move the base vector out. This
// saves one complete memory pass while retaining the existing std::vector API.
// The fallback remains fully portable (but pays the zero-fill) on other STLs.
#if defined(__GLIBCXX__)
static_assert(
    _GLIBCXX_RELEASE == 11 &&
        __GLIBCXX__ == 20230528 &&
        __GNUC__ == 11 &&
        __GNUC_MINOR__ == 4,
    "DirectOutputVector is pinned to GCC 11.4/libstdc++ 11 (20230528); "
    "audit the vector layout and rerun Random differential/sanitizer tests "
    "before changing this guard");

template<typename T>
class DirectOutputVector final : public std::vector<T>
{
    static_assert(
        std::is_trivial_v<T> &&
            std::is_trivially_destructible_v<T>,
        "direct output storage is only valid for trivial scalar values");

public:
    explicit DirectOutputVector(
        std::size_t size)
    {
        // Avoid even null + 0 pointer arithmetic on an empty allocation.
        if (size == 0)
        {
            return;
        }
        this->reserve(size);
        T* const begin = this->data();
        for (std::size_t index = 0;
             index < size;
             ++index)
        {
            ::new (static_cast<void*>(begin + index)) T;
        }
        this->_M_impl._M_finish =
            this->_M_impl._M_start + size;
    }

    std::vector<T> release() && noexcept
    {
        auto& base =
            static_cast<std::vector<T>&>(*this);
        return std::move(base);
    }
};

template<typename T>
std::vector<T> direct_output_vector(
    std::size_t size)
{
    return DirectOutputVector<T>(size)
        .release();
}
#else
template<typename T>
std::vector<T> direct_output_vector(
    std::size_t size)
{
    return std::vector<T>(size);
}
#endif

#if defined(__AVX2__)
using CompactIndices =
    std::array<std::array<std::int32_t, 8>, 256>;

constexpr CompactIndices make_compact_indices()
{
    CompactIndices table{};
    for (std::size_t mask = 0;
         mask < table.size();
         ++mask)
    {
        std::size_t output = 0;
        for (std::int32_t lane = 0;
             lane < 8;
             ++lane)
        {
            if ((mask & (std::size_t{1} << lane)) != 0)
            {
                table[mask][output++] = lane;
            }
        }
        while (output < 8)
        {
            table[mask][output++] = 0;
        }
    }
    return table;
}

alignas(32) constexpr CompactIndices
    compact_indices = make_compact_indices();
#endif

template<typename Function>
void parallel_chunks(
    std::size_t size,
    Function function,
    std::size_t parallel_threshold = 262144)
{
    const unsigned available =
        std::thread::hardware_concurrency();
    const std::size_t thread_count =
        size < parallel_threshold || available < 2
        ? 1
        : std::min<std::size_t>(available, 8);

    if (thread_count == 1)
    {
        function(0, size);
        return;
    }

    std::vector<std::thread> workers;
    workers.reserve(thread_count - 1);
    const std::size_t block =
        (size + thread_count - 1) / thread_count;

    try
    {
        for (std::size_t worker = 1;
             worker < thread_count;
             ++worker)
        {
            const std::size_t begin = worker * block;
            const std::size_t end =
                std::min(size, begin + block);
            workers.emplace_back(
                [=, &function]
                {
                    if (begin < end)
                    {
                        function(begin, end);
                    }
                });
        }
        function(0, std::min(size, block));
    }
    catch (...)
    {
        for (std::thread& worker : workers)
        {
            worker.join();
        }
        throw;
    }

    for (std::thread& worker : workers)
    {
        worker.join();
    }
}

